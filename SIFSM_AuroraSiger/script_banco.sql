-- Limpeza (ignore os erros caso as tabelas ainda não existam)
DROP TABLE T_SIFSM_ALERTA  CASCADE CONSTRAINTS;
DROP TABLE T_SIFSM_LEITURA CASCADE CONSTRAINTS;
DROP TABLE T_SIFSM_MODULO  CASCADE CONSTRAINTS;

-- -------------------------------------------------------------
-- Tabela 1: módulos da colônia (habitação, agricultura, energia...)
-- -------------------------------------------------------------
CREATE TABLE T_SIFSM_MODULO (
    cod_modulo           VARCHAR2(10)  PRIMARY KEY,          -- ex.: HAB-01
    nome                 VARCHAR2(60)  NOT NULL,
    tipo                 VARCHAR2(20)  NOT NULL,             -- HABITACAO, AGRICULTURA...
    critico              NUMBER(1)     DEFAULT 0 NOT NULL
                         CHECK (critico IN (0, 1)),          -- 1 = suporte à vida
    status               VARCHAR2(12)  DEFAULT 'ATIVO' NOT NULL
                         CHECK (status IN ('ATIVO', 'MANUTENCAO', 'INATIVO')),
    consumo_nominal_kwh  NUMBER(8,2)   NOT NULL CHECK (consumo_nominal_kwh > 0)
);

-- -------------------------------------------------------------
-- Tabela 2: leituras dos sensores simulados (1 por módulo por sol)
-- -------------------------------------------------------------
CREATE TABLE T_SIFSM_LEITURA (
    id_leitura        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    cod_sensor        VARCHAR2(15)  NOT NULL,                -- ex.: SNS-HAB-01
    cod_modulo        VARCHAR2(10)  NOT NULL
                      REFERENCES T_SIFSM_MODULO (cod_modulo),
    sol               NUMBER(5)     NOT NULL CHECK (sol >= 1), -- dia marciano
    ocupacao          NUMBER(3)     DEFAULT 0 NOT NULL,      -- tripulantes no módulo
    temp_externa_c    NUMBER(6,1),
    temp_interna_c    NUMBER(6,1),
    luminosidade_lux  NUMBER(8,1),
    umidade_pct       NUMBER(5,1)   CHECK (umidade_pct BETWEEN 0 AND 100),
    opacidade_poeira  NUMBER(4,2),                           -- tau atmosférico
    consumo_kwh       NUMBER(8,2)   NOT NULL CHECK (consumo_kwh >= 0),
    presenca          NUMBER(1)     DEFAULT 0 CHECK (presenca IN (0, 1)),
    falha_sensor      NUMBER(1)     DEFAULT 0 CHECK (falha_sensor IN (0, 1))
);

-- -------------------------------------------------------------
-- Tabela 3: alertas gerados pela regra booleana / análise
-- -------------------------------------------------------------
CREATE TABLE T_SIFSM_ALERTA (
    id_alerta    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    cod_modulo   VARCHAR2(10)  NOT NULL REFERENCES T_SIFSM_MODULO (cod_modulo),
    sol          NUMBER(5)     NOT NULL,
    nivel        VARCHAR2(10)  NOT NULL,                     -- CRITICO / ATENCAO
    prioridade   NUMBER(1)     NOT NULL,                     -- 1 = mais urgente
    descricao    VARCHAR2(200) NOT NULL,
    status       VARCHAR2(12)  DEFAULT 'ABERTO' NOT NULL
);

-- Índices para as consultas mais frequentes
CREATE INDEX IX_LEITURA_MODULO_SOL ON T_SIFSM_LEITURA (cod_modulo, sol);
CREATE INDEX IX_LEITURA_SENSOR     ON T_SIFSM_LEITURA (cod_sensor);

